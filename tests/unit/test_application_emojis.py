@pytest.mark.asyncio
async def test_already_uploaded_emojis_are_resolved_without_uploading():
    import clashcontrol.emojis as emojis
    from clashcontrol.emojis import BotEmojis, load_emoji_manifest

    manifest = load_emoji_manifest()
    bot = MagicMock()
    bot.fetch_application_emojis = AsyncMock(return_value=[
        _emoji(entry["name"], 1552060584176914000 + i) for i, entry in enumerate(manifest)
    ])
    bot.create_application_emoji = AsyncMock()

    resolved = await emojis.ensure_application_emojis(bot, background=False)

    assert resolved == len(manifest)
    bot.create_application_emoji.assert_not_awaited()
    assert BotEmojis.ENABLED.startswith("<:enabled:1552060584176914")


@pytest.mark.asyncio
async def test_only_missing_emojis_are_uploaded_from_their_webp(monkeypatch):
    import clashcontrol.emojis as emojis
    from clashcontrol.emojis import BotEmojis, load_emoji_manifest

    monkeypatch.setattr(emojis, "UPLOAD_PACING_SECONDS", 0)
    manifest = load_emoji_manifest()
    present = [e for e in manifest if e["name"] != "cwl_bench"]

    bot = MagicMock()
    bot.fetch_application_emojis = AsyncMock(return_value=[
        _emoji(e["name"], 1552060584176914000 + i) for i, e in enumerate(present)
    ])
    bot.create_application_emoji = AsyncMock(return_value=_emoji("cwl_bench", 1552060584176914515))

    await emojis.ensure_application_emojis(bot, background=False)

    bot.create_application_emoji.assert_awaited_once()
    kwargs = bot.create_application_emoji.await_args.kwargs
    assert kwargs["name"] == "cwl_bench"
    assert kwargs["image"][0:4] == b"RIFF" and kwargs["image"][8:12] == b"WEBP"
    assert BotEmojis.CWL_BENCH == "<:cwl_bench:1552060584176914515>"


@pytest.mark.asyncio
async def test_a_first_start_uploads_in_the_background_without_blocking(monkeypatch):
    """~34 uploads on the first start must never hold up the boot sequence."""
    import sys

    import clashcontrol.emojis as emojis

    spawned = []
    fake_qbcore = MagicMock()
    fake_qbcore.spawn_tracked = MagicMock(side_effect=lambda name, coro: spawned.append((name, coro)))
    monkeypatch.setitem(sys.modules, "QBcore", fake_qbcore)

    bot = MagicMock()
    bot.fetch_application_emojis = AsyncMock(return_value=[])
    bot.create_application_emoji = AsyncMock()

    resolved = await emojis.ensure_application_emojis(bot)

    assert resolved == 0
    assert len(spawned) == 1 and spawned[0][0] == "upload-application-emojis"
    bot.create_application_emoji.assert_not_awaited()  # nothing uploaded inline
    spawned[0][1].close()  # don't leave the never-awaited coroutine behind


@pytest.mark.asyncio
async def test_one_failed_upload_does_not_stop_the_rest(monkeypatch):
    import clashcontrol.emojis as emojis
    from clashcontrol.emojis import BotEmojis

    monkeypatch.setattr(emojis, "UPLOAD_PACING_SECONDS", 0)
    calls = {"n": 0}

    async def flaky(name, image):
        calls["n"] += 1
        if name == "enabled":
            raise RuntimeError("Discord rejected it")
        return _emoji(name, 1552060584176915000 + calls["n"])

    bot = MagicMock()
    bot.fetch_application_emojis = AsyncMock(return_value=[])
    bot.create_application_emoji = AsyncMock(side_effect=flaky)

    await emojis.ensure_application_emojis(bot, background=False)

    assert BotEmojis.ENABLED == "<:enabled:1455513859715629076>"  # kept its fallback
    assert BotEmojis.DISABLED.startswith("<:disabled:155206058417691")  # the rest went through


