def test_manifest_and_botemojis_cover_each_other_exactly():
    """A BotEmojis constant without a manifest entry would never become an application emoji; a
    manifest entry without a constant would be uploaded but unreachable from the code."""
    from clashcontrol.emojis import load_emoji_manifest

    manifest_attrs = {entry["attr"] for entry in load_emoji_manifest()}
    assert manifest_attrs == _botemoji_attrs()


def test_manifest_names_are_valid_and_unique():
    from clashcontrol.emojis import load_emoji_manifest

    names = [entry["name"] for entry in load_emoji_manifest()]
    assert len(names) == len(set(names))
    for name in names:
        assert _NAME_RULE.match(name), name


def test_every_manifest_master_exists():
    from clashcontrol.emojis import load_emoji_manifest

    icons = os.path.join("clashcontrol", "icons")
    for entry in load_emoji_manifest():
        assert os.path.exists(os.path.join(icons, entry["source"])), entry


def test_every_upload_file_is_square_lossless_webp_under_the_limit():
    """Generated by build-emoji-assets.mjs and committed. Lossless matters: lossy WebP smears the
    thin edges these small icons are made of. Read straight from the VP8L header, no Pillow."""
    from clashcontrol.emojis import emoji_asset_path, load_emoji_manifest

    for entry in load_emoji_manifest():
        path = emoji_asset_path(entry["name"])
        assert os.path.exists(path), f"missing {path} — run `npm run build:emoji` in activity/client"
        data = open(path, "rb").read()
        assert len(data) <= 256 * 1024, f"{entry['name']}: over Discord's 256 KiB limit"
        assert data[0:4] == b"RIFF" and data[8:12] == b"WEBP", entry["name"]
        assert data[12:16] == b"VP8L", f"{entry['name']}: not LOSSLESS WebP"
        bits = int.from_bytes(data[21:25], "little")
        width, height = (bits & 0x3FFF) + 1, ((bits >> 14) & 0x3FFF) + 1
        assert width == height, f"{entry['name']}: {width}x{height} is not square"
        assert width <= 128, f"{entry['name']}: {width}px exceeds Discord's 128px emoji size"


