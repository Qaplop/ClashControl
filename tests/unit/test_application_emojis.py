"""Every custom emoji is an application emoji the bot owns (plans/app-emoji-migration.md).

The manifest (clashcontrol/icons/emoji_manifest.json) lists each icon; the generator
(activity/client/scripts/build-emoji-assets.mjs) turns its master into a lossless square WebP;
the bot uploads missing ones and resolves BotEmojis attributes to them at lookup time, keeping the
old guild-emoji ids as fallbacks.
"""
from __future__ import annotations

import os
import re
from unittest.mock import AsyncMock, MagicMock

import pytest

_UPPER_ATTR = re.compile(r"^[A-Z][A-Z0-9_]*$")
_NAME_RULE = re.compile(r"^\w{2,32}$")  # Discord: >= 2 chars, alphanumerics and underscores


@pytest.fixture(autouse=True)
def _isolated_resolution():
    import clashcontrol.emojis as emojis

    saved = dict(emojis._resolved)
    emojis._resolved.clear()
    yield
    emojis._resolved.clear()
    emojis._resolved.update(saved)


def _botemoji_attrs() -> set[str]:
    from clashcontrol.emojis import BotEmojis

    return {name for name in vars(BotEmojis) if _UPPER_ATTR.match(name)}


def _emoji(name: str, emoji_id: int) -> MagicMock:
    emoji = MagicMock()
    emoji.name = name
    emoji.id = emoji_id
    emoji.__str__ = lambda self: f"<:{name}:{emoji_id}>"  # type: ignore[assignment]
    return emoji


